"use client";

import { useState } from "react";
import { StCard, StCardHead, StCardHint, StCardTitle, StGhostBtn, StGuide } from "../page.styles";
import type { TournamentEvent } from "./types";

type Props = { event: TournamentEvent };

// 참가자용 안내: 게임 방식 + 토너먼트 방식. 처음엔 접혀 있다
export default function TournamentGuide({ event }: Props) {
  const [open, setOpen] = useState(false);
  return (
    <StCard>
      <StCardHead>
        <StCardTitle>📖 대회 방식 안내</StCardTitle>
        <StGhostBtn type="button" onClick={() => setOpen((v) => !v)}>
          {open ? "접기" : "펼치기"}
        </StGhostBtn>
      </StCardHead>
      <StCardHint>처음 오신 분도 이 글만 읽으면 돼요. 게임은 어떻게 하고, 토너먼트는 어떻게 이어지는지.</StCardHint>
      {!open ? null : (
        <StGuide>
          <h4>🎾 게임 방식</h4>
          <ul>
            <li>
              <b>2:2 복식</b>이에요. 한 경기는 <b>{event.gamesToWin}게임을 먼저 따는 팀</b>이 이겨요. 예) 6:3, 6:5.
            </li>
            <li>
              <b>5:5</b>가 되면 게임을 더 하지 않고 <b>7점 타이브레이크</b>로 승부를 가려요. 7점을 먼저 내되 2점 차가 나야 끝나요. 이긴 팀은 6:5로 적고 타이브레이크 점수(예: 7-4)를 함께 적어요.
            </li>
            <li>
              팀은 4명이고 팀 안에 시드 1~4번이 있어요. 한 경기 안에서 <b>4게임마다 페어를 바꿔요.</b>
              <br />
              1~4게임 <b>페어A</b> = 시드 2번 + 4번 → 5~8게임 <b>페어B</b> = 시드 1번 + 3번 → 9~12게임(연장 시) <b>페어C</b> = 시드 1번 + 2번
              <br />
              4게임(짝수) 단위라 그 블록에 나온 두 사람이 서브 게임을 한 번씩 공평하게 나눠 가져요. 이 순서는 모든 경기에서 똑같이 A→B→C예요.
            </li>
            <li>
              시드 1·2번은 세 페어 중 두 개에 들어가서 3·4번보다 더 자주 뛰어요. 경기 카드에 우리 팀 페어 구성이 이름으로 떠 있으니 그걸 보고 코트에 들어가면 돼요.
            </li>
            <li>경기당 예상 {event.minutesPerMatch}분이고, 코트는 A~D 4면을 써요.</li>
          </ul>

          <h4>🏆 토너먼트 방식 — 더블 엘리미네이션</h4>
          <ul>
            <li>
              <b>두 번 져야 탈락</b>이에요. 한 번 지면 끝이 아니라 <b>패자조</b>로 내려가서 다시 기회를 받아요.
            </li>
            <li>
              <b>1라운드</b>: 8팀 전원이 4경기를 해요 (1·2번 시드, 3·4번, 5·6번, 7·8번). 이긴 4팀은 <b>승자조 4강</b>, 진 4팀은 <b>패자조 1라운드</b>로 가요.
            </li>
            <li>
              <b>승자조</b>는 4강 → 결승으로 올라가요. 승자조에서 진 팀은 그 시점의 패자조로 합류해요. 4강에서 진 팀은 패자조 2라운드, 결승에서 진 팀은 패자조 결승으로.
            </li>
            <li>
              <b>패자조</b>는 1라운드 → 2라운드 → 준결승 → 결승 순서예요. 여기서 지면 두 번째 패배라 탈락(순위결정전)으로 가요.
            </li>
            <li>
              <b>그랜드 파이널</b>: 승자조 우승팀 vs 패자조 우승팀. 승자조 우승팀이 이기면 바로 우승이에요. 패자조 우승팀이 이기면 서로 1패씩이라 <b>리셋 재경기</b>를 한 번 더 해서 우승을 정해요.
            </li>
            <li>
              <b>순위결정전</b>으로 1~8위를 모두 정해요. 7-8위전은 패자조 1라운드에서 진 두 팀, 5-6위전은 패자조 2라운드에서 진 두 팀, 3-4위전은 패자조 준결승 패자 vs 패자조 결승 패자.
            </li>
          </ul>

          <h4>🕒 하루 흐름</h4>
          <ul>
            <li>{event.beforeNote || "개회식 · 몸풀기"} → 1타임 1라운드(4코트) → 2타임 승자조 4강 + 패자조 1R(4코트) → 3타임 승자조 결승 + 패자조 2R + 7-8위전(4코트)</li>
            <li>4타임 패자조 준결승 + 5-6위전(A·B) → 5타임 패자조 결승(A) → 6타임 그랜드 파이널 + 3-4위전(A·B) → 필요하면 7타임 리셋 재경기(A)</li>
            <li>{event.afterNote || "시상식 · 폐회식"}. 3타임까지는 4코트가 다 돌고, 그 뒤엔 남는 팀이 줄어 일부 코트가 쉬어요. 더블 엘리미네이션 구조상 어쩔 수 없는 부분이에요.</li>
          </ul>

          <h4>📱 점수 넣는 법</h4>
          <ul>
            <li>경기 시작 때 카드의 <b>&ldquo;코트 X에서 시작&rdquo;</b>을 누르고, 끝나면 게임 수를 넣고 <b>&ldquo;경기 끝 · 점수 저장&rdquo;</b>을 눌러요. 이긴 팀이 넣는 걸로 정하면 헷갈리지 않아요.</li>
            <li>저장하면 다음 경기에 팀이 자동으로 채워지고, 다른 사람 화면에도 곧 보여요. 잘못 넣었으면 &ldquo;고치기&rdquo;로 바로잡아요.</li>
          </ul>
        </StGuide>
      )}
    </StCard>
  );
}
